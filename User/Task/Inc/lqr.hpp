    /* 根据腿长更新使用的矩阵k */
    void Update(float _llen, float _rlen, bool _stay)
    {
        _llen = (_llen < MIN_LEG_LEN) ? MIN_LEG_LEN : _llen;
        _llen = (_llen > MAX_LEG_LEN) ? MAX_LEG_LEN : _llen;
        _rlen = (_rlen < MIN_LEG_LEN) ? MIN_LEG_LEN : _rlen;
        _rlen = (_rlen > MAX_LEG_LEN) ? MAX_LEG_LEN : _rlen;
        //保留两位小数
        _llen = roundf(_llen * 100) / 100.0f;
        _rlen = roundf(_rlen * 100) / 100.0f;

        /* a1 + a2*L_len + a3*R_len + a4*L_len^2 + a5*L_len*R_len + a6*R_len^2 */ 
        if (lqr_type == LQR_LOW)
        {
            for(int i = 0; i < 40; i++)
            {
                LQRKBuf[i] = LQRKLowcoeffs[i][0] + LQRKLowcoeffs[i][1] * _llen + LQRKLowcoeffs[i][2] * _rlen + LQRKLowcoeffs[i][3] * _llen * _llen + LQRKLowcoeffs[i][4] * _llen * _rlen + LQRKLowcoeffs[i][5] * _rlen * _rlen;
            }
        }
        else 
        {
            for(int i = 0; i < 40; i++)
            {
                LQRKBuf[i] = LQRKHighcoeffs[i][0] + LQRKHighcoeffs[i][1] * _llen + LQRKHighcoeffs[i][2] * _rlen + LQRKHighcoeffs[i][3] * _llen * _llen + LQRKHighcoeffs[i][4] * _llen * _rlen + LQRKHighcoeffs[i][5] * _rlen * _rlen;
            }
        }


        /* [Tl;Tr;Tpl;Tpr] = -K(X_obs - X_ref) */
        // 1. Calculate Error: X_err = X_obs - X_ref
        float err[10] = {0};
        for (int i=0; i<10; i++)
        {
            err[i] = this->LQRXObsX[i] - this->LQRXRefX[i];
        }

        // if (_stay)
        // {
        //     err[0] *= 1.5f;
        //     err[1] *= 1.5f;
        // }
        
        // 2. Calculate U = -K * X_err
        // Matrix multiplication: [4x10] * [10x1] = [4x1]
        for (int i=0; i<4; i++)
        {
            float temp = 0.0f;
            for (int j=0; j<10; j++)
            {
                temp += LQRKBuf[i*10+j]*err[j];
            }   
            Tout[i] = temp;
        }
    }
